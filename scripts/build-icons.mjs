// Generates src/styles/icons.generated.css: data URI glyphs exposed as
// `--icon-*` custom properties.
//
// CSS-painted glyphs only; markup uses src/components/Icon.astro
import { readFileSync, renameSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { icons } from '@iconify-json/ion'
import { getIconData, iconToHTML, iconToSVG, svgToURL } from '@iconify/utils'

const USED = ['md-arrow-forward']

// Fill variants, percent-encoded so a raw comma can't end the data URI
const FILLS = {
  '': 'rgb(0%2C0%2C0)',
  '-white': 'rgb(255%2C255%2C255)'
}

// Stands in for `fill="currentColor"` while the SVG is encoded
const FILL = '__ICON_FILL__'

const output = fileURLToPath(
  new URL('../src/styles/icons.generated.css', import.meta.url)
)

function render() {
  const entries = USED.flatMap((name) => {
    // getIconData() merges the set's 512x512 default; per-icon records
    // have no width/height of their own
    const icon = getIconData(icons, name)
    if (!icon) throw new Error(`Unknown icon in the "ion" set: ${name}`)

    const { body, viewBox } = iconToSVG(icon)
    const svg = iconToHTML(body.replaceAll('currentColor', FILL), {
      viewBox: viewBox.join(' '),
      width: `${viewBox[2]}`,
      height: `${viewBox[3]}`
    })

    const encoded = svgToURL(svg).slice(
      'url("data:image/svg+xml,'.length,
      -'")'.length
    )

    return Object.entries(FILLS).map(
      ([suffix, fill]) =>
        `  --icon-${name}${suffix}: url("data:image/svg+xml,${encoded.replaceAll(FILL, fill)}");`
    )
  })

  return [
    '/* GENERATED by scripts/build-icons.mjs - do not edit */',
    '/* Regenerate with: pnpm icons */',
    '',
    ':root {',
    ...entries,
    '}',
    ''
  ].join('\n')
}

function current() {
  try {
    return readFileSync(output, 'utf8')
  } catch {
    return ''
  }
}

const next = render()

if (next === current()) {
  console.log('icons.generated.css is up to date')
} else if (process.argv.includes('--check')) {
  console.error('icons.generated.css is stale; run pnpm icons')
  process.exit(1)
} else {
  // Written to a temp file first: `pnpm ci` runs `icons:check` and `build` concurrently
  writeFileSync(`${output}.tmp`, next)
  renameSync(`${output}.tmp`, output)
  console.log('wrote src/styles/icons.generated.css')
}
